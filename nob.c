#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#define NOB_IMPLEMENTATION
#include "./nob.h"

Nob_Cmd cmd = {0};

void generate_scancodes() {
    if (nob_file_exists("./scancodes.c")) return;

    Nob_String_Builder sb = {0};
    nob_sb_append_cstr(&sb, "// NOTE: generated by nob\n");
    nob_sb_append_cstr(&sb, "#include <linux/input-event-codes.h>\n\n");
    nob_sb_append_cstr(&sb, "char scancode_to_ascii(int scancode) {\n");
    nob_sb_append_cstr(&sb, "\tswitch (scancode) {\n");
    for (char i = 'a'; i<'z'; i++) {
        nob_sb_append_cstr(&sb, "\t\tcase KEY_");
        nob_sb_append(&sb, toupper(i));
        nob_sb_append_cstr(&sb, ": return \'");
        nob_sb_append(&sb, i);
        nob_sb_append_cstr(&sb, "\';\n");
    }
    nob_sb_append_cstr(&sb, "\t\tdefault: return \'0\';\n");
    nob_sb_append_cstr(&sb, "\t}\n}\n");

    if (!nob_write_entire_file("./scancodes.c", sb.items, sb.count)) {
        printf("failed to generate scancodes.c\n");
        exit(1);
    }

}

int main(int argc, char *argv[]) {
    NOB_GO_REBUILD_URSELF(argc, argv);
    generate_scancodes();
    nob_cmd_append(&cmd, "clang");
    nob_cmd_append(&cmd, "-lwayland-client", "-lwayland-egl", "-lEGL", "-lGL", "-lm", "-lSDL3_ttf", "-lSDL3");
    nob_cmd_append(&cmd, "./main.c", "./protocol/wlr-layer-shell-unstable-v1.c", "./protocol/xdg-shell.c", "./glad.c", "./scancodes.c");
    nob_cmd_append(&cmd, "-o", "sofi");

    if (!nob_cmd_run(&cmd)) return 1;

    nob_cmd_append(&cmd, "clang");
    nob_cmd_append(&cmd, "./worker.c");
    nob_cmd_append(&cmd, "-o", "sofi_worker");

    if (!nob_cmd_run(&cmd)) return 1;

    return 0;
}
